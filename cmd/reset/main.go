// Command reset generates Reset() methods for structs marked with
// the "// generate:reset" comment. Methods of each package are written
// to reset.gen.go in that package's directory.
//
// Usage: go run ./cmd/reset [root]   (root defaults to ".")
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const (
	marker  = "generate:reset"
	outFile = "reset.gen.go"
)

var basicZero = map[string]string{
	"bool": "false", "string": `""`,
	"int": "0", "int8": "0", "int16": "0", "int32": "0", "int64": "0",
	"uint": "0", "uint8": "0", "uint16": "0", "uint32": "0", "uint64": "0", "uintptr": "0",
	"float32": "0", "float64": "0", "complex64": "0", "complex128": "0",
	"byte": "0", "rune": "0",
	"error": "nil", "any": "nil",
}

func main() {
	root := "."
	if len(os.Args) > 1 {
		root = os.Args[1]
	}
	if err := run(root); err != nil {
		fmt.Fprintln(os.Stderr, "reset:", err)
		os.Exit(1)
	}
}

func run(root string) error {
	var dirs []string
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() {
			return nil
		}
		dirs = append(dirs, path)
		return nil
	})
	if err != nil {
		return err
	}
	for _, dir := range dirs {
		if err := processDir(dir); err != nil {
			return fmt.Errorf("%s: %w", dir, err)
		}
	}
	return nil
}

type target struct {
	name   string
	st     *ast.StructType
	file   *ast.File
	fset   *token.FileSet
	tparam bool
}

func processDir(dir string) error {
	fset := token.NewFileSet()
	pkgs, err := parser.ParseDir(fset, dir, func(fi fs.FileInfo) bool {
		n := fi.Name()
		return n != outFile
	}, parser.ParseComments)
	if err != nil {
		return err
	}
	for n, pn := range pkgs {
		if err := processPkg(dir, fset, n, pn); err != nil {
			return err
		}
	}
	return nil
}

func processPkg(dir string, fset *token.FileSet, pkgName string, pkg *ast.Package) error {
	var targets []target
	hasReset := map[string]bool{}

	fnames := make([]string, 0, len(pkg.Files))
	for n := range pkg.Files {
		fnames = append(fnames, n)
	}
	sort.Strings(fnames)

	for _, fn := range fnames {
		f := pkg.Files[fn]
		for _, decl := range f.Decls {
			switch d := decl.(type) {
			case *ast.FuncDecl:
				if d.Recv != nil && d.Name.Name == "Reset" && len(d.Recv.List) == 1 {
					if n := recvName(d.Recv.List[0].Type); n != "" {
						hasReset[n] = true
					}
				}
			case *ast.GenDecl:
				if d.Tok != token.TYPE {
					continue
				}
				for _, spec := range d.Specs {
					ts := spec.(*ast.TypeSpec)
					st, ok := ts.Type.(*ast.StructType)
					if !ok {
						continue
					}
					if hasMarker(d.Doc) || hasMarker(ts.Doc) {
						targets = append(targets, target{
							name: ts.Name.Name, st: st, file: f, fset: fset,
							tparam: ts.TypeParams != nil && len(ts.TypeParams.List) > 0,
						})
					}
				}
			}
		}
	}
	// Marked structs will have Reset generated.
	for _, t := range targets {
		hasReset[t.name] = true
	}
	out := filepath.Join(dir, outFile)
	if len(targets) == 0 {
		// Remove stale generated file.
		if _, err := os.Stat(out); err == nil {
			return os.Remove(out)
		}
		return nil
	}

	imports := map[string]string{} // local name -> import line
	var body bytes.Buffer
	for _, t := range targets {
		if t.tparam {
			fmt.Fprintf(os.Stderr, "reset: skipping generic struct %s\n", t.name)
			continue
		}
		g := &gen{t: t, hasReset: hasReset, imports: imports}
		fmt.Fprintf(&body, "// Reset resets %s to its initial state.\nfunc (s *%s) Reset() {\n", t.name, t.name)
		body.WriteString("\tif s == nil {\n\t\treturn\n\t}\n")
		for _, fld := range t.st.Fields.List {
			if len(fld.Names) == 0 { // embedded
				name := embeddedName(fld.Type)
				if name == "" {
					continue
				}
				g.value(&body, "s."+name, fld.Type, 1)
				continue
			}
			for _, n := range fld.Names {
				if n.Name == "_" {
					continue
				}
				g.value(&body, "s."+n.Name, fld.Type, 1)
			}
		}
		body.WriteString("}\n\n")
	}

	var buf bytes.Buffer
	buf.WriteString("// Code generated by cmd/reset; DO NOT EDIT.\n\n")
	fmt.Fprintf(&buf, "package %s\n\n", pkgName)
	if len(imports) > 0 {
		keys := make([]string, 0, len(imports))
		for k := range imports {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		buf.WriteString("import (\n")
		for _, k := range keys {
			buf.WriteString("\t" + imports[k] + "\n")
		}
		buf.WriteString(")\n\n")
	}
	buf.Write(body.Bytes())
	src, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("format generated code: %w\n%s", err, buf.String())
	}
	fmt.Println("generated", out)
	return os.WriteFile(out, src, 0o644)
}

type gen struct {
	t        target
	hasReset map[string]bool
	imports  map[string]string
}

func ind(n int) string { return strings.Repeat("\t", n) }

// value emits code resetting lvalue x of type expression typ.
func (g *gen) value(w *bytes.Buffer, x string, typ ast.Expr, depth int) {
	p := ind(depth)
	switch t := typ.(type) {
	case *ast.ParenExpr:
		g.value(w, x, t.X, depth)
	case *ast.Ident:
		if z, ok := basicZero[t.Name]; ok {
			fmt.Fprintf(w, "%s%s = %s\n", p, x, z)
		} else if g.hasReset[t.Name] {
			fmt.Fprintf(w, "%s%s.Reset()\n", p, x)
		} else {
			fmt.Fprintf(w, "%s%s = *new(%s)\n", p, x, t.Name)
		}
	case *ast.SelectorExpr:
		// Type from another package: call Reset() if it has one, otherwise zero it.
		ts := g.typeString(typ)
		fmt.Fprintf(w, "%sif r, ok := any(&%s).(interface{ Reset() }); ok {\n%s\tr.Reset()\n%s} else {\n%s\t%s = *new(%s)\n%s}\n",
			p, x, p, p, p, x, ts, p)
	case *ast.StarExpr:
		fmt.Fprintf(w, "%sif %s != nil {\n", p, x)
		g.value(w, "(*"+x+")", t.X, depth+1)
		fmt.Fprintf(w, "%s}\n", p)
	case *ast.ArrayType:
		if t.Len == nil { // slice
			fmt.Fprintf(w, "%s%s = %s[:0]\n", p, x, x)
		} else {
			fmt.Fprintf(w, "%s%s = *new(%s)\n", p, x, g.typeString(typ))
		}
	case *ast.MapType:
		fmt.Fprintf(w, "%sclear(%s)\n", p, x)
	case *ast.ChanType, *ast.FuncType, *ast.InterfaceType:
		fmt.Fprintf(w, "%s%s = nil\n", p, x)
	default: // anonymous struct etc.
		fmt.Fprintf(w, "%s%s = *new(%s)\n", p, x, g.typeString(typ))
	}
}

// typeString prints a type and records the imports it needs.
func (g *gen) typeString(e ast.Expr) string {
	ast.Inspect(e, func(n ast.Node) bool {
		if se, ok := n.(*ast.SelectorExpr); ok {
			if id, ok := se.X.(*ast.Ident); ok {
				g.addImport(id.Name)
			}
		}
		return true
	})
	var b bytes.Buffer
	_ = printer.Fprint(&b, g.t.fset, e)
	return b.String()
}

func (g *gen) addImport(name string) {
	for _, is := range g.t.file.Imports {
		path := strings.Trim(is.Path.Value, `"`)
		local := filepath.Base(path)
		line := is.Path.Value
		if is.Name != nil {
			local = is.Name.Name
			line = local + " " + is.Path.Value
		}
		if local == name {
			g.imports[local] = line
			return
		}
	}
}

func hasMarker(cg *ast.CommentGroup) bool {
	if cg == nil {
		return false
	}
	for _, c := range cg.List {
		text := strings.TrimSpace(strings.TrimPrefix(c.Text, "//"))
		if text == marker {
			return true
		}
	}
	return false
}

func recvName(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.StarExpr:
		return recvName(t.X)
	case *ast.Ident:
		return t.Name
	case *ast.IndexExpr:
		return recvName(t.X)
	}
	return ""
}

func embeddedName(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.StarExpr:
		return embeddedName(t.X)
	case *ast.Ident:
		return t.Name
	case *ast.SelectorExpr:
		return t.Sel.Name
	}
	return ""
}
